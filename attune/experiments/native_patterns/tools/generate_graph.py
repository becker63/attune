"""Assemble ordinary declared Bazel actions; performs no scientific evaluation."""
from pathlib import Path
import argparse
import json

parser = argparse.ArgumentParser()
parser.add_argument('--experiment', type=Path, required=True)
parser.add_argument('--workspace', type=Path, required=True)
parser.add_argument('--output', type=Path)
args = parser.parse_args()
experiment = args.experiment
package = args.workspace / 'experiments/native_patterns'
worlds = json.loads((experiment / 'worlds.json').read_text())
tasks = [t for t in json.loads((experiment / 'tasks.json').read_text()) if t['replay_state'] == 'Completed']
base = ['//src:Attune.flix', '//src:Attune/Effects.flix', '//src:Attune/Artifacts.flix', 'Campaign.flix']
repository = ['//src:Attune/Coverage.flix', '//src:Attune/Repository.flix', '//src:Attune/Repository/Grit.flix']
theory = ['//src:Attune/Theory.flix', '//src:Attune/Patterns.flix', '//src:Attune/Studio.flix']
grit = ['//platform/tools/grit:attune_grit']
lines = ['# Generated by tools/generate_graph.py. This file assembles native Flix actions.',
         'load("//platform/build:native.bzl", "flix_action", "native_flix_test")',
         'load("@rules_java//java:defs.bzl", "java_library")',
         'package(default_visibility = ["//visibility:public"])',
         'filegroup(name="policy_files", srcs=glob(["**/*.flix", "**/*.java", "*.bazel", "*.md", "tools/*.py", "tools/*.sh"], allow_empty=True))']

def external(name):
    return '@native_campaign_inputs//:' + name

def action(name, sources, inputs=None, java=None, native=False):
    fields = dict(name=name, srcs=sources, inputs=inputs or {}, java_deps=java or [], timeout_seconds=600, tags=['manual'])
    if native:
        fields['native_libs'] = ['//platform/support/grit:attune_grit_abi']
    lines.append('flix_action(\n' + ''.join('    ' + k + ' = ' + repr(v) + ',\n' for k, v in fields.items()) + ')')

def group(name, targets):
    lines.append('filegroup(name=' + repr(name) + ', srcs=' + repr(targets) + ', tags=["manual"])')

lines.extend([
    'native_flix_test(name="pattern_law_test", srcs=["PatternLaw.flix", "//src:Attune.flix", "//src:Attune/Coverage.flix", "//src:Attune/Patterns.flix"])',
    'native_flix_test(name="metric_campaign_test", srcs=["MetricCampaignLaw.flix", "//src:Attune.flix", "//src:Attune/Study.flix"])',
    'java_library(name="legacy_grit", srcs=["legacy/AttuneGrit.java"], deps=["//platform/tools/grit:attune_grit", "@attune_maven//:com_fasterxml_jackson_core_jackson_databind"])'])

for world in worlds:
    wid = world['world']
    action('extract_' + wid, base + repository + ['Extract.flix'], {'source': external(wid + '-source.json')}, grit, True)
    action('admit_' + wid, base + repository + ['Admit.flix'], {'observations': ':extract_' + wid, 'world': external(wid + '-world.json'), 'recipe': external('recipe.json')}, grit)
    legacy = ['legacy/Attune.flix', 'legacy/Attune/Coverage.flix', 'legacy/Attune/Repository.flix', 'legacy/Attune/Repository/Grit.flix']
    action('legacy_' + wid, legacy + base[1:] + ['LegacyAdmit.flix'], {'observations': ':extract_' + wid}, [':legacy_grit'])

for task in tasks:
    tid, wid = task['task'], task['world']
    vector_inputs = {'source': external(wid + '-source.json'), 'query': external(tid + '-query.json'), 'task': external(tid + '-task.json'), 'query-vector': external(tid + '-vector.tsv'), 'code-vectors': external(wid + '-vectors.tsv')}
    action('q_' + tid, base + ['Campaign/Replay.flix', 'Rank.flix'], vector_inputs)
    action('qlegacy_' + tid, base + ['Campaign/Replay.flix', 'LegacyEmbedding.flix', 'RankLegacy.flix'], vector_inputs)
    action('match_' + tid, base + repository + theory + ['Match.flix'], {'admitted': ':admit_' + wid, 'ranking': ':q_' + tid}, grit)
    action('predict_' + tid, base + repository + ['//src:Attune/Theory.flix', '//src:Attune/Studio.flix', 'Predict.flix'], {'ranking': ':q_' + tid, 'matches': ':match_' + tid, 'configs': external('configs.json')}, grit)
    action('eval_' + tid, base + ['//src:Attune/Study.flix', 'Evaluate.flix'], {'task': external(tid + '-task.json'), 'predictions': ':predict_' + tid, 'labels': external('labels.json')})
    action('jev_' + tid, base + repository + ['//src:Attune/Theory.flix', '//src:Attune/Studio.flix', 'Jev.flix'], {'enabled': external('jev-enabled.json'), 'selected': external('jev-selected.json'), 'receipts': external('jev-receipts.json'), 'query': external(tid + '-query.json'), 'source': external(wid + '-source.json'), 'predictions': ':predict_' + tid, 'matches': ':match_' + tid}, grit)

summary_inputs = {'tasks': external('metric-tasks.json'), 'costs': external('costs.json')} | {t['task']: ':eval_' + t['task'] for t in tasks}
action('selection', base + ['//src:Attune/Study.flix', 'Summarize.flix'], summary_inputs | {'phase': external('selection-phase.json')})
action('summary', base + ['//src:Attune/Study.flix', 'Summarize.flix'], summary_inputs | {'phase': external('report-phase.json'), 'selection': ':selection'})
action('finite', base + ['//src:Attune/Coverage.flix', '//src:Attune/Patterns.flix', 'PatternPermutation.flix', 'Finite.flix'], {'cases': external('finite.json')})
action('core_current', base + ['CoreReplay.flix'])
action('core_legacy', ['legacy/Attune.flix'] + base[1:] + ['CoreReplay.flix'])
for fixture in ['a', 'b', 'c']:
    action('eval_fixture-' + fixture, base + ['//src:Attune/Study.flix', 'Evaluate.flix'], {'task': external('fixture-' + fixture + '-task.json'), 'predictions': external('fixture-predictions.json'), 'labels': external('fixture-labels.json')})
action('summary_fixture', base + ['//src:Attune/Study.flix', 'Summarize.flix'], {'phase': external('fixture-phase.json'), 'tasks': external('fixture-tasks.json'), 'costs': external('fixture-costs.json')} | {'fixture-' + f: ':eval_fixture-' + f for f in ['a', 'b', 'c']})
group('primary', [':predict_' + t['task'] for t in tasks])
group('all_admitted', [':admit_' + w['world'] for w in worlds])
group('legacy_all', [':legacy_' + w['world'] for w in worlds])
group('qlegacy_all', [':qlegacy_' + t['task'] for t in tasks])
group('science_payloads', [':' + stage + '_' + w['world'] for w in worlds for stage in ['extract', 'admit']] + [':' + stage + '_' + t['task'] for t in tasks for stage in ['q', 'match', 'predict']])
group('recompute_tasks', [':' + stage + '_' + t['task'] for t in tasks for stage in ['q', 'match']])
group('evaluation_payloads', [':eval_' + t['task'] for t in tasks] + [':selection', ':summary'])
unavailable_path = experiment / 'execution-unavailable-worlds.json'
unavailable = json.loads(unavailable_path.read_text()) if unavailable_path.exists() else {}
for task in tasks:
    if task['world'] in unavailable:
        action('unavailable_' + task['task'], base + ['Unavailable.flix'], {'ranking': ':q_' + task['task'], 'configs': external('configs.json'), 'failure': external('failure-' + task['world'] + '.json')})
        old = "'predictions': ':predict_" + task['task'] + "'"
        new = "'predictions': ':unavailable_" + task['task'] + "'"
        lines = [line.replace(old, new) if "name = 'eval_" in line or "name = 'jev_" in line else line for line in lines]
group('available_science_payloads', [':' + stage + '_' + w['world'] for w in worlds if w['world'] not in unavailable for stage in ['extract', 'admit', 'legacy']] + [':q_' + t['task'] for t in tasks] + [':qlegacy_' + t['task'] for t in tasks] + [(':unavailable_' + t['task']) if t['world'] in unavailable else (':predict_' + t['task']) for t in tasks] + [':match_' + t['task'] for t in tasks if t['world'] not in unavailable])
# Independent action identities force computation while retaining exact semantic
# inputs. The six-world panel was selected by size/language before outcomes.
panel = json.loads((experiment / 'recompute-panel.json').read_text())
recomputed = []
for wid in panel:
    if wid in unavailable:
        continue
    action('rextract_' + wid, base + repository + ['Extract.flix'], {'source': external(wid + '-source.json')}, grit, True)
    action('radmit_' + wid, base + repository + ['Admit.flix'], {'observations': ':rextract_' + wid, 'world': external(wid + '-world.json'), 'recipe': external('recipe.json')}, grit)
    recomputed.extend([':rextract_' + wid, ':radmit_' + wid])
for task in tasks:
    tid, wid = task['task'], task['world']
    vector_inputs = {'source': external(wid + '-source.json'), 'query': external(tid + '-query.json'), 'task': external(tid + '-task.json'), 'query-vector': external(tid + '-vector.tsv'), 'code-vectors': external(wid + '-vectors.tsv')}
    action('rq_' + tid, base + ['Campaign/Replay.flix', 'Rank.flix'], vector_inputs)
    recomputed.append(':rq_' + tid)
    if wid not in unavailable:
        action('rmatch_' + tid, base + repository + theory + ['Match.flix'], {'admitted': (':radmit_' if wid in panel else ':admit_') + wid, 'ranking': ':rq_' + tid}, grit)
        action('rpredict_' + tid, base + repository + ['//src:Attune/Theory.flix', '//src:Attune/Studio.flix', 'Predict.flix'], {'ranking': ':rq_' + tid, 'matches': ':rmatch_' + tid, 'configs': external('configs.json')}, grit)
        recomputed.extend([':rmatch_' + tid, ':rpredict_' + tid])
group('independent_recompute', recomputed)
extra_graph = package / 'scratch/graph.bzl.txt'
if extra_graph.exists():
    lines.append(extra_graph.read_text())
    action('match_vector_receipt', base + repository + theory + ['Match.flix'], {'admitted': ':admit_w69', 'ranking': ':probe_vector'}, grit)
    action('predict_vector_receipt', base + repository + ['//src:Attune/Theory.flix', '//src:Attune/Studio.flix', 'Predict.flix'], {'ranking': ':probe_vector', 'matches': ':match_vector_receipt', 'configs': external('scratch-configs.json')}, grit)
    group('vector_receipt_chain', [':probe_vector', ':match_vector_receipt', ':predict_vector_receipt'])
(args.output or package / 'BUILD.bazel').write_text('\n\n'.join(lines) + '\n')
