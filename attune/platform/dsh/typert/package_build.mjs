/// The declared installable-package builder of the narrow evidence contract.
///
/// This module runs inside a declared Bazel action (`//platform/dsh:typert_package`
/// via the `typert_build` js_binary). It is the ONE place the real pinned
/// `@deepseek-ai/dsh-typert-generator` 0.2.0-rc.2 analyzer/emitter runs as a
/// build step rather than inside a test: it copies the declared contributor
/// fixture into a scratch workspace, generates the transport declaration, and
/// assembles the installable Cordis package.
///
/// It decides no policy and adds no second schema authority. The generated bytes
/// are the generator's own; the authored `install/` inputs are copied verbatim;
/// and the emitted manifest, surface and digest are deterministic, so two builds
/// of the same declared inputs are byte-identical.
///
/// @module attune.typert.package-build

import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, copyFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

import { WorkspaceAnalyzer, WorkspaceTypertGenerator } from '@deepseek-ai/dsh-typert-generator'
import { canonicalSurface, contractDigest } from './bridge.mjs'

/// The declared contributor package the generator analyzes.
const PACKAGE = '@attune/evidence-contract'
/// The contract version the emitted identity carries.
const CONTRACT = 'attune.evidence-substrate/2'

function parseArgs(argv) {
  const args = {}
  for (let index = 0; index < argv.length; index += 2) {
    args[argv[index].replace(/^--/, '')] = argv[index + 1]
  }
  return args
}

/// A dereferencing copy: the declared fixture may arrive through the runfiles
/// tree, so every entry is followed to its real bytes and written as an ordinary
/// writable file. The scratch copy is what the generator mutates.
function copyTree(source, target) {
  const info = statSync(source)
  if (info.isDirectory()) {
    mkdirSync(target, { recursive: true })
    for (const entry of readdirSync(source).sort()) copyTree(join(source, entry), join(target, entry))
  } else {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, readFileSync(source))
  }
}

/// The selected reflection of the contributor package, exactly as the parity law
/// reads it: the declarations the package owns with their member names, in
/// canonical order.
function reflectedSurface(root) {
  const analyzer = new WorkspaceAnalyzer({ root })
  const model = analyzer.analyze()
  const face = model.faces.find((candidate) => candidate.face === 'host')
  if (face === undefined) throw new Error('the host face must be analyzed')
  const declarations = face.graph.declarations
    .filter((declaration) => declaration.package === PACKAGE)
    .sort((left, right) => left.name.localeCompare(right.name))
  const lines = []
  for (const declaration of declarations) {
    lines.push(declaration.name)
    for (const member of [...declaration.members].sort((left, right) => left.name.localeCompare(right.name))) {
      lines.push(`${declaration.name}.${member.name}`)
    }
  }
  return canonicalSurface(lines)
}

/// Deterministic JSON: a stable key order (the authored object's own insertion
/// order, which the author controls) and a trailing newline.
function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`
}

function main() {
  const args = parseArgs(process.argv.slice(2))
  const fixture = resolve(args.fixture)
  const install = resolve(args.install)
  const out = resolve(args.out)

  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })

  // 1. The scratch workspace the real generator analyzes and writes into.
  const scratch = join(out, 'scratch')
  copyTree(join(fixture, 'tsconfig.host.json'), join(scratch, 'tsconfig.host.json'))
  copyTree(join(fixture, 'packages'), join(scratch, 'packages'))

  const generator = new WorkspaceTypertGenerator(scratch)
  const discovered = generator.discover()
  const artifacts = generator.generate()
  const discoveredPackages = discovered.map((entry) => entry.package).sort()
  if (discoveredPackages.length !== 1 || discoveredPackages[0] !== PACKAGE) {
    throw new Error(`the real generator must discover exactly ${PACKAGE}, saw ${JSON.stringify(discoveredPackages)}`)
  }

  // 2. The installable package tree.
  const pkg = join(out, 'package')
  mkdirSync(join(pkg, 'lib'), { recursive: true })
  for (const artifact of artifacts) {
    if (artifact.packageRoot !== 'packages/attune-evidence') {
      throw new Error(`unexpected generated package root ${artifact.packageRoot}`)
    }
    writeFileSync(join(pkg, 'lib', `typert.${artifact.face}.js`), artifact.js)
    writeFileSync(join(pkg, 'lib', `typert.${artifact.face}.d.ts`), artifact.dts)
  }

  // The contract identity, emitted beside the declaration so the runtime entry
  // reads one identity rather than recomputing a second one.
  const surface = reflectedSurface(scratch)
  const digest = contractDigest(CONTRACT, surface)
  if (digest === undefined) throw new Error('the selected contract surface could not be computed')
  writeFileSync(
    join(pkg, 'lib', 'contract.digest.js'),
    `// Generated by //platform/dsh:typert_package. Do not edit.\n` +
      `export const CONTRACT = ${JSON.stringify(CONTRACT)}\n` +
      `export const DIGEST = ${JSON.stringify(digest)}\n`,
  )
  writeFileSync(
    join(pkg, 'lib', 'contract.digest.d.ts'),
    `export declare const CONTRACT: string\n` +
      `export declare const DIGEST: string\n`,
  )

  // The authored Cordis entry and bundle patch are copied verbatim into the
  // package; the generator's own artifacts stay the transport declaration. The
  // source interface declarations are shipped as the package's root types, so
  // the generated declaration's reference to `@attune/evidence-contract`
  // resolves to the same contract the generator analyzed.
  copyFileSync(join(install, 'entry.mjs'), join(pkg, 'lib', 'index.js'))
  copyFileSync(join(install, 'entry.d.ts'), join(pkg, 'lib', 'index.d.ts'))
  copyFileSync(join(install, 'cordis.patch.yml'), join(pkg, 'cordis.patch.yml'))
  mkdirSync(join(pkg, 'lib', 'types'), { recursive: true })
  copyFileSync(
    join(fixture, 'packages', 'attune-evidence', 'src', 'index.ts'),
    join(pkg, 'lib', 'types', 'index.d.ts'),
  )
  writeFileSync(join(pkg, 'package.json'), readFileSync(join(install, 'manifest.json')))

  // 3. The declared evidence of this build action: the canonical surface, the
  // contract digest and the selected reflection. A consumer compares these
  // against the frozen parity fixture and the canonical Flix meaning.
  writeFileSync(
    join(out, 'surface.txt'),
    `# ${CONTRACT} — the selected canonical exported surface emitted by the real generator.\n` +
      surface.map((line) => `${line}\n`).join(''),
  )
  writeFileSync(join(out, 'digest.txt'), `${digest}\n`)
  writeFileSync(join(out, 'reflection.json'), json({ package: PACKAGE, contract: CONTRACT, surface }))

  // The scratch workspace is build scratch, not part of the declared outputs.
  rmSync(scratch, { recursive: true, force: true })
}

main()
